/** Every old Docusaurus path under /docs/, as slug segments. */
export function legacyDocSlugs(): string[][] {
  return [...Object.keys(pages), ...apiSlugs.map((slug) => `api/${slug}`)].map(
    (path) => path.split('/'),
  )
}

/** The new URL for an old /docs/ path, or null when it was never a page. */
export function legacyDocTarget(slug: string[]): string | null {
  const path = slug.join('/')
  const target =
    pages[path] ??
    (slug[0] === 'api' && apiSlugs.includes(slug.slice(1).join('/'))
      ? '/api/'
      : null)
  if (!target) return null
  return target.startsWith('http') ? target : `${basePath}${target}`
}
